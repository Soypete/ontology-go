package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"path/filepath"
	"text/template"
)

var (
	specFile    string
	outputFile  string
	packageName string
)

func init() {
	flag.StringVar(&specFile, "spec", "calculus.json", "Path to calculus spec JSON file")
	flag.StringVar(&outputFile, "output", "generated.go", "Output file for generated code")
	flag.StringVar(&packageName, "package", "gorr", "Package name for generated code")
	flag.Parse()
}

type ExprKind struct {
	Name        string   `json:"name"`
	Description string   `json:"description"`
	Arguments   []string `json:"arguments,omitempty"`
}

type ConclusionKind struct {
	Name        string `json:"name"`
	Description string `json:"description"`
}

type InferenceType struct {
	Name       string   `json:"name"`
	Conclusion string   `json:"conclusion"`
	Premises   []string `json:"premises"`
}

type RuleDef struct {
	Name       string `json:"name"`
	Number     int    `json:"number"`
	Conclusion string `json:"conclusion"`
	Premises   string `json:"premises"`
}

type CalculusSpec struct {
	ExprKinds       []ExprKind       `json:"expr_kinds"`
	ConclusionKinds []ConclusionKind `json:"conclusion_kinds"`
	InferenceTypes  []InferenceType  `json:"inference_types"`
	Rules           []RuleDef        `json:"rules"`
}

func main() {
	specPath := specFile
	if !filepath.IsAbs(specPath) {
		wd, _ := os.Getwd()
		specPath = filepath.Join(wd, specPath)
	}

	data, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatalf("Failed to read spec file: %v", err)
	}

	var spec CalculusSpec
	if err := json.Unmarshal(data, &spec); err != nil {
		log.Fatalf("Failed to parse spec JSON: %v", err)
	}

	var buf bytes.Buffer
	if err := generateCode(&buf, &spec); err != nil {
		log.Fatalf("Failed to generate code: %v", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Printf("Warning: Failed to format generated code: %v", err)
		formatted = buf.Bytes()
	}

	outPath := outputFile
	if !filepath.IsAbs(outPath) {
		wd, _ := os.Getwd()
		outPath = filepath.Join(wd, outPath)
	}

	if err := os.WriteFile(outPath, formatted, 0644); err != nil {
		log.Fatalf("Failed to write output: %v", err)
	}

	fmt.Printf("Generated %s from %s\n", outPath, specPath)
}

