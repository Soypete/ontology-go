func generateCode(w io.Writer, spec *CalculusSpec) error {
	data := map[string]interface{}{
		"Package":         packageName,
		"ExprKinds":       spec.ExprKinds,
		"ConclusionKinds": spec.ConclusionKinds,
		"InferenceTypes":  spec.InferenceTypes,
		"Rules":           spec.Rules,
	}
	return codeTemplate.Execute(w, data)
}
